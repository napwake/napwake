// vetTags are the tags make vet vets every package with.
var vetTags = regexp.MustCompile(`(?m)^\tgo vet -tags ([a-z0-9_,]+) \./\.\.\.$`)

// Every build tag a Go file is built only with, such as e2e, sizing or
// soak, is one the linter builds and make vet vets, so a test run only by
// hand can't stop compiling unseen, as test/sizing could (P82). A tag a
// file is built without, such as controller-gen's !ignore_autogenerated,
// needs nothing.
func TestEveryBuildTagIsBuiltInCI(t *testing.T) {
	cmd := exec.Command("git", "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", "*.go")
	cmd.Dir = repoRoot
	out, err := cmd.Output()
	require.NoError(t, err, "listing the tree's files takes a git work tree")
	used := map[string][]string{}
	for file := range strings.SplitSeq(strings.TrimSuffix(string(out), "\x00"), "\x00") {
		data, err := os.ReadFile(filepath.Join(repoRoot, file))
		if os.IsNotExist(err) {
			continue // deleted, not yet staged
		}
		require.NoError(t, err)
		line, _, _ := strings.Cut(string(data), "\n")
		if !constraint.IsGoBuild(line) {
			continue
		}
		expr, err := constraint.Parse(line)
		require.NoError(t, err, file)
		for _, tag := range requiredTags(expr) {
			used[tag] = append(used[tag], file)
		}
	}
	require.Contains(t, used, "e2e", "the e2e suite's tag is found")

	var lint struct {
		Run struct {
			BuildTags []string `json:"build-tags"`
		} `json:"run"`
	}
	config, err := os.ReadFile(filepath.Join(repoRoot, ".golangci.yml"))
	require.NoError(t, err)
	require.NoError(t, yaml.Unmarshal(config, &lint))
	makefile, err := os.ReadFile(filepath.Join(repoRoot, "Makefile"))
	require.NoError(t, err)
	m := vetTags.FindSubmatch(makefile)
	require.NotNil(t, m, "make vet runs go vet -tags ... ./...")
	vetted := strings.Split(string(m[1]), ",")

	for tag, files := range used {
		assert.Contains(t, lint.Run.BuildTags, tag, ".golangci.yml's run.build-tags lacks %s, which %v need", tag, files)
		assert.Contains(t, vetted, tag, "make vet's -tags lacks %s, which %v need", tag, files)
	}
}

// requiredTags are the tags a constraint is satisfied only with, as far
// as it names them outside a negation.
func requiredTags(expr constraint.Expr) []string {
	switch e := expr.(type) {
	case *constraint.TagExpr:
		return []string{e.Tag}
	case *constraint.AndExpr:
		return slices.Concat(requiredTags(e.X), requiredTags(e.Y))
	case *constraint.OrExpr:
		return slices.Concat(requiredTags(e.X), requiredTags(e.Y))
	}
	return nil
}
